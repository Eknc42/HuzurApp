// Belirli bir ruh hali için rastgele bir ayet getir
export function getVerseForMood(moodId) {
  const moodVerses = VERSES[moodId];
  if (!moodVerses || moodVerses.length === 0) return null;
  const randomIndex = Math.floor(Math.random() * moodVerses.length);
  return moodVerses[randomIndex];
}

// Bir ruh hali için tüm ayetleri getir
export function getVersesForMood(moodId) {
  return VERSES[moodId] || [];
}
